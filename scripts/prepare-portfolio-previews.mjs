// Mechanical publishing derivatives: preserve source pixels locally, never redesign UI.
// Run manually with the existing Sharp runtime; CI consumes the generated previews.
import { createRequire } from 'node:module';
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import { resolve, relative } from 'node:path';

const require = createRequire(import.meta.url);
const sharp = require(process.env.DESIGN_SHARP_MODULE || 'sharp');
const originals = resolve('.local-asset-archive/portfolio-image-originals');
const output = resolve('public/assets/previews');
await mkdir(output, { recursive: true });
const assets = {};
const groups = [
  { folder: 'one-to-z', key: name => `one-to-z:${name.replace(/^one-to-z-/, '')}`, name: name => name },
  { folder: 'designgraphy', key: name => `designgraphy:${name}`, name: name => `designgraphy-${name}` },
  { folder: 'project-evidence', key: name => `evidence:${name.startsWith('design-pick-') ? 'design-pick' : name.startsWith('naratmalsami-') ? 'naratmalsami' : name.startsWith('planor-') ? 'planor' : ''}`, name: name => `evidence-${name}` },
];
for (const group of groups) {
  const directory = resolve(originals, group.folder);
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    if (!entry.isFile() || !/^[a-z0-9-]+\.(?:webp|jpg)$/i.test(entry.name)) throw new Error(`Unexpected source: ${entry.name}`);
    const name = entry.name.replace(/\.[^.]+$/, '');
    const id = group.key(name);
    if (id.endsWith(':') || assets[id]) throw new Error(`Invalid or duplicate preview: ${id}`);
    const source = resolve(directory, entry.name);
    const filename = `${group.name(name)}-preview.webp`;
    const target = resolve(output, filename);
    if (relative(directory, source).startsWith('..') || relative(output, target).startsWith('..')) throw new Error('Asset outside allowed directory');
    const { width, height } = await sharp(source)
      .resize({ width: 1200, height: 2400, fit: 'inside', withoutEnlargement: true })
      .removeAlpha().webp({ quality: 78, effort: 5 }).toFile(target);
    assets[id] = { image: `/assets/previews/${filename}`, width, height };
  }
}
// Generated metadata is a mechanical asset manifest, not hand-written product code.
await writeFile('src/data/imagePreviewAssets.ts', `// Generated by scripts/prepare-portfolio-previews.mjs. Public derivatives only.\nexport interface ImagePreviewAsset { image: string; width: number; height: number }\nexport const imagePreviewAssets: Readonly<Record<string, ImagePreviewAsset>> = ${JSON.stringify(assets, null, 2)};\n`);
console.log(JSON.stringify({ previews: Object.keys(assets).length, maxWidth: 1200, maxHeight: 2400, watermark: 'none' }));
